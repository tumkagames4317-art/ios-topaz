#!/bin/bash
# ============================================================================
# migcom shim around Debian's x86_64-gnu-migcom (package: mig-x86-64-gnu).
#
# mig.sh (Apple's driver, unmodified) forwards its switches straight to
# migcom. Several of those are Apple-only and GNU migcom rejects them
# outright with "fatal: unknown flag". Migcom also expects its input in a
# different order than Apple's: GNU mig requires the `subsystem` statement
# before any type is looked up, while Apple's .defs put `#include`s first.
#
# This shim does two things and nothing else:
#   (a) drop the Apple-only switches, echoing each drop to stderr so it is
#       never a silent behaviour change;
#   (b) hoist the `subsystem NAME ID;` statement to the top of the input.
#
# migcom reads the .defs from STDIN (mig.sh pipes cpp output into it), so the
# input is buffered, optionally reordered, and passed on stdin.
#
# This file lives in the repo rather than being generated by printf inside
# the workflow: writing it via YAML meant escaping an awk program through
# two layers of quoting, which produced invalid bash repeatedly. A checked-in
# file is reviewable, diffable, and needs no escaping.
# ============================================================================
set -u

real="__MIGCOM_REAL__"

args=()
dropped=""
while [ $# -gt 0 ]; do
  case "$1" in
    -novouchers|-mach_msg2|-split)
      dropped="$dropped $1"; shift ;;
    -maxonstack|-max_descrs|-max_reply_descrs)
      dropped="$dropped $1 $2"; shift 2 ;;
    *)
      args+=("$1"); shift ;;
  esac
done

[ -n "$dropped" ] && echo "migcom-shim: dropped:$dropped" >&2

inp=$(mktemp)
hoisted=$(mktemp)
trap 'rm -f "$inp" "$hoisted"' EXIT

cat > "$inp"

# No subsystem statement: nothing to hoist, pass straight through.
if ! grep -qE '^[[:space:]]*subsystem([[:space:]]|$)' "$inp"; then
  exec "$real" "${args[@]}" < "$inp"
fi

# Hoist everything from the first `subsystem` up to its terminating `;` to
# the very top, preserving the rest of the file in order. Preprocessor #line
# markers are left untouched, so compiler diagnostics still name real lines.
awk '
  BEGIN { grab = 0; nb = 0; ss = "" }
  # NOTE the ([[:space:]]|$) alternation. Apple writes the keyword on a line
  # of its own with NOTHING after it:
  #     subsystem
  #     #ifdef KERNEL_USER
  #     KernelUser
  #     #endif
  #     lockd_mach 1023;
  # so `subsystem[[:space:]]` cannot match -- [[:space:]] needs a character
  # after the keyword and there is none. That one missing alternation made
  # the hoist fail with rc=3 on every real lockd_mach.defs; verified locally
  # against the preprocessed shape, which keeps the #line markers.
  /^[[:space:]]*subsystem([[:space:]]|$)/ { grab = 1 }
  grab {
    ss = ss $0 "\n"
    if ($0 ~ /;[[:space:]]*$/) { grab = 0; nb++ }
    next
  }
  { lines[++n] = $0 }
  END {
    if (nb != 1) exit 3
    printf "%s", ss
    for (i = 1; i <= n; i++) print lines[i]
  }
' "$inp" > "$hoisted"

awk_rc=$?
if [ "$awk_rc" -ne 0 ]; then
  echo "migcom-shim: WARNING: could not hoist subsystem (awk rc=$awk_rc); passing through unchanged" >&2
  exec "$real" "${args[@]}" < "$inp"
fi

echo "migcom-shim: hoisted subsystem statement to top of input" >&2
exec "$real" "${args[@]}" < "$hoisted"
